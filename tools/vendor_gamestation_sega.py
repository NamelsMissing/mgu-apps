#!/usr/bin/env python3
"""Bundle the MIT-licensed jsmoo SMS/GG core for Node.js 8 from a pinned checkout."""
import pathlib
import subprocess
import sys

REVISION = '359d18e6ea8a8c1e275954d097071b83e6fdbd24'
APP = pathlib.Path(__file__).resolve().parents[1] / 'apps/mgu_gamestation'
FILES = [
    'component/cpu/z80/z80_opcodes.js',
    'component/cpu/z80/z80_generated_opcodes.js',
    'component/cpu/z80/z80.js',
    'component/controller/sms_joypad.js',
    'component/audio/sn76489/sn76489.js',
    'system/sms_gg/sms_gg_mapper_sega.js',
    'system/sms_gg/sms_gg_io.js',
    'system/sms_gg/sms_gg_vdp.js',
    'system/sms_gg/sms_gg.js',
    'helpers/presenters/sms_gg_presenter.js',
]
ROOT = pathlib.Path(sys.argv[1])


def source(file):
    return subprocess.check_output(['git', '-C', str(ROOT), 'show', REVISION + ':' + file]).decode()


def replace(text, old, new):
    if text.count(old) != 1:
        raise ValueError(old)
    return text.replace(old, new)


def adapt(file, text):
    if file.endswith('/z80.js'):
        text = replace(text, 'this.NMI_pending ||= level;', 'this.NMI_pending = this.NMI_pending || level;')
    if file.endswith('/sms_gg.js'):
        # Machine-description API is for the browser and unused by the app.
        start = text.index('let SMS_inputmap')
        text = text[:start] + text[text.index('const SER_SMSGG_clock', start):]
        start = text.index('    get_description()')
        text = text[:start] + text[text.index('    step_scanlines', start):]
        text = replace(text, 'if (variant !== SMSGG_variants.GG)\n            this.load_bios();',
                       'if (bios.loaded && variant !== SMSGG_variants.GG)\n            this.load_bios();')
        text = replace(text, 'while(current_frame === this.clock.frames_since_restart) {',
                       'while(current_frame === this.clock.frames_since_restart) {\n'
                       "            if (scanlines_done > 263) throw new Error('Sega frame timed out');")
    if file.endswith('/sms_gg_mapper_sega.js'):
        text = replace(text, 'if (r !== null) {', 'if (r !== null && r !== undefined) {')
    if file.endswith('/sms_gg_vdp.js'):
        text = text.replace('new SharedArrayBuffer(', 'new ArrayBuffer(')
    if file.endswith('/sms_gg_io.js'):
        text = replace(text, 'this.portA.attached_device = this.controllerA;',
                       'this.portA.attached_device = this.controllerA;\n'
                       '        if (variant !== SMSGG_variants.GG) {\n'
                       '            this.controllerB = new SMSGG_gamepad(variant, 2);\n'
                       '            this.portB.attached_device = this.controllerB;\n'
                       '        }')
        text = replace(text, '//this.controllerB.buffer_input(inp2);',
                       'if (this.controllerB) this.controllerB.buffer_input(inp2);')
        text = replace(text, 'return 0x40 | (this.gg_joymap.start ? 0x80 : 0);',
                       'return 0x40 | (this.gg_joymap.start ? 0 : 0x80);')
        text = replace(text, 'cpu_out_gg(addr, val) {\n        addr &= 0xFF;',
                       'cpu_out_gg(addr, val) {\n        addr &= 0xFF;\n'
                       '        if (addr === 6) { this.sn76489.stereo = val; return; }')
    if file.endswith('/sn76489.js'):
        text = replace(text, 'mix_sample() {', 'mix_sample(mask = 15) {')
        text = replace(text, 'if (this.sw[i].freq > 7)', 'if ((mask & (1 << i)) && this.sw[i].freq > 7)')
        text = replace(text, 'sample += ((this.polarity[3] * 2) - 1) * intensity;',
                       'if (mask & 8) sample += ((this.polarity[3] * 2) - 1) * intensity;')
        text = replace(text, 'this.output.sample(this.mix_sample());',
                       'if (this.capture) this.capture(this);\n'
                       '            else this.output.sample(this.mix_sample());')
    if file.endswith('/sms_gg_presenter.js'):
        text = replace(text, 'let brl = 224; // data.bottom_rendered_line', 'let brl = data.bottom_rendered_line;')
    return '\n'.join(line.rstrip() for line in text.splitlines())


preamble = """'use strict';
// jsmoo SMS/GG / MIT, see JSMOO_LICENSE.txt. Generated by tools/vendor_gamestation_sega.py.
(function () {
const REGION = {NTSC: 0, NTSCJ: 1, PAL: 2};
const D_RESOURCE_TYPES = {Z80: 0};
const dbg = {add_cpu() {}, remove_cpu() {}, break() {}};
const console = {log() {}, warn() {}, error() {}};
const hex2 = n => n.toString(16);
const hex4 = hex2;
const mksigned8 = value => (value << 24) >> 24;
"""
tail = """
module.exports = {SMSGG, SMSGG_variants, REGION, SMS_present, GG_present};
})();
"""
with (APP / 'sega_vendor.js').open('w', encoding='utf8') as out:
    out.write(preamble)
    for file in FILES:
        out.write('\n// ' + file + '\n' + adapt(file, source(file)) + '\n')
    out.write(tail)
(APP / 'JSMOO_LICENSE.txt').write_text(source('license.txt'), encoding='utf8')
